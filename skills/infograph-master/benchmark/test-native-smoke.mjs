import assert from 'node:assert/strict';
import {readFile,mkdir,mkdtemp,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
import {planRuns,runOne,validateResume} from './run-pilot.mjs';
import {collectRuns} from './collect-runs.mjs';
import {analyzePairs} from './benchmark-analytics.mjs';
import {analyzeReviewed} from './review-analysis.mjs';
import {normalizeReview} from './normalize-review.mjs';
import {scoreRun} from './score.mjs';
import {buildReview} from './blind-review.mjs';
const read=async n=>JSON.parse(await readFile(new URL(n,import.meta.url),'utf8'));
const schedule=await read('pilot-schedule.json'),base=(await read('baseline-packets.json')).packets,enh=(await read('enhanced-packets.json')).packets,rubric=await read('rubric.json');
const plan=planRuns(schedule,base,enh,{limit:24});assert.equal(plan.length,24);
const first=plan[0],second=plan.find(p=>p.model===first.model&&p.task===first.task&&p.rep===first.rep&&p.arm!==first.arm);assert.ok(second);
const root=resolve(process.env.SMOKE_OUT||await mkdtemp(join(tmpdir(),'infograph-')));await mkdir(root,{recursive:true});const runs=join(root,'runs'),screens=join(root,'screens'),blind=join(root,'blind');await mkdir(runs);
const records=[];
for(const p of [first,second]){
 const record=await runOne(p,{baseUrl:'https://mock.invalid/v1',key:'mock-only',model:'mock-model',out:runs,fetcher:async()=>new Response(JSON.stringify({model:'mock-model',usage:{prompt_tokens:100,completion_tokens:50},choices:[{finish_reason:'stop',message:{content:'<!doctype html><html><meta name="viewport" content="width=device-width"><body><h1>Synthetic smoke fixture</h1></body></html>'}}]}))});
 assert.equal(record.status,'completed');assert.equal(record.inputTokens,100);records.push(record);
}
for(const p of [first,second])assert.equal((await validateResume(p,{out:runs,model:'mock-model'})).status,'completed');
await assert.rejects(validateResume(first,{out:runs,model:'different-model'}),/settings mismatch/);
await assert.rejects(validateResume({...first,promptHash:'wrong'},{out:runs,model:'mock-model'}),/identity mismatch/);
const artifact=join(runs,first.runId,'artifact.html'),original=await readFile(artifact,'utf8');
await writeFile(artifact,original.replace('Synthetic','Modified'));
await assert.rejects(validateResume(first,{out:runs,model:'mock-model'}),/artifact mismatch/);
await writeFile(artifact,original);
const fixture=await read('analytics.example.json');assert.deepEqual(analyzePairs(fixture.schedule,fixture.records),fixture.result);
execFileSync(process.execPath,[new URL('evaluate-artifacts.mjs',import.meta.url).pathname,runs,screens],{stdio:'inherit',timeout:120000});
const report=JSON.parse(await readFile(join(screens,'engineering-report.json'),'utf8'));assert.equal(report.results.length,2);assert.ok(report.results.every(r=>r.status==='observed-pass'&&r.cases.length===2));
assert.equal(await buildReview(runs,screens,blind),2);
const manifest=JSON.parse(await readFile(join(blind,'review','manifest.json'),'utf8'));assert.equal(manifest.items.length,2);assert.ok(manifest.items.every(x=>!('runId' in x)&&x.images.length===2));
const normalized=records.map(r=>({...r,score:scoreRun({hardFails:[],applicable:Object.keys(rubric.weights),scores:Object.fromEntries(Object.keys(rubric.weights).map(k=>[k,r.arm==='full'?4:3]))},rubric).score}));
const result=analyzePairs(schedule,collectRuns(schedule,normalized).records);assert.equal(result.metrics.score.meanDelta,20);assert.equal(result.metrics.score.n,1);
await writeFile(join(root,'smoke-result.json'),JSON.stringify({synthetic:true,status:'passed',result},null,2));console.log('Synthetic integration smoke passed',root);

const blindKey=JSON.parse(await readFile(join(blind,'PRIVATE-key.json'),'utf8'));
const item=blindKey[0],ratings=Object.fromEntries(Object.keys(rubric.weights).map(k=>[k,4]));
const input={review:{version:'0.1',scope:'screenshots-only',reviewer:'synthetic',records:[{id:item.blindId,task:item.task,scores:ratings}]},key:blindKey,records,applicability:{[item.task]:Object.keys(rubric.weights)},adjudications:{},rubric};
assert.equal(normalizeReview(input)[0].status,'not-run');
input.adjudications[item.runId]={hardFailReview:'complete',hardFails:[]};
assert.equal(normalizeReview(input)[0].status,'not-run');
input.adjudications[item.runId].verifiedScores={interaction:4,engineering:4};
assert.equal(normalizeReview(input)[0].score,80);
input.adjudications[item.runId].hardFails=[rubric.hardFails[0]];
assert.equal(normalizeReview(input)[0].status,'fail');
input.review.records[0].scores.visual=6;
assert.throws(()=>normalizeReview(input),/invalid review rating/);

input.review.records[0].scores.visual=4;
input.adjudications[item.runId].hardFails=[];
const settingsByRun=Object.fromEntries(records.map(r=>[r.runId,{model:'mock-model',max_tokens:8192,temperature:0.2}]));
const analysisInput={...input,schedule,settingsByRun,reviews:[input.review]};
const reviewed=analyzeReviewed(analysisInput);
assert.equal(reviewed.reviewSummary.scored,1);
assert.equal(reviewed.reviewSummary['not-run'],1);
assert.equal(reviewed.analysis.metrics.score.n,0);
assert.throws(()=>analyzeReviewed({...analysisInput,reviews:[input.review,input.review]}),/duplicate reviewer/);
settingsByRun[second.runId].temperature=0.7;
assert.throws(()=>analyzeReviewed(analysisInput),/mixed model settings/);
