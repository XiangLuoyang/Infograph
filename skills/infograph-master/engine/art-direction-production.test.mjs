import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {compileArtDirections,selectArtDirection,artDirectionCSS,artDirectionPreview} from './art-direction-production.mjs';
const load=p=>JSON.parse(readFileSync(new URL(p,import.meta.url),'utf8'));
const presets=load('./art-directions.json'),styles=load('./styles.json');
const brief={purpose:'report',theme:'Synthetic capacity constraint',readerTask:'Compare capacity with demand',density:'normal',evidenceRef:'synthetic brief'};
const compile=x=>compileArtDirections(x,presets,styles);
const p=compile(brief);
assert.equal(p.candidates.length,3);
assert.ok(p.candidates.every(c=>c.contrast.every(x=>x.ratio>=x.minimum)));
assert.equal(p.candidates[0].typography.heading,'serif');
assert.equal(p.candidates[1].geometry.frame,'open');
assert.equal(p.candidates[2].geometry.frame,'rule');
assert.equal(compile({...brief,purpose:'monitor'}).candidates[0].id,'technical');
assert.equal(compile({...brief,purpose:'explore'}).candidates[0].id,'architectural');
assert.equal(compile({...brief,density:'dense'}).candidates[0].typography.bodyPx,14);
assert.equal(compile({...brief,density:'presentation'}).candidates[0].typography.bodyPx,18);
const all=compile({...brief,families:['technical','analytical','architectural','swiss','editorial']});
assert.equal(all.candidates.length,5);
assert.ok(all.candidates.every(c=>c.contrast.every(x=>x.ratio>=x.minimum)));
for(const bad of [{...brief,families:['editorial','swiss','technical']},{...brief,families:['analytical','analytical','technical']},{...brief,theme:''},{...brief,density:'unknown'}])assert.throws(()=>compile(bad));
const selected=selectArtDirection(all,'technical','synthetic material comparison');
assert.equal(selected.rejected.length,4);
assert.throws(()=>selectArtDirection(all,'other','reason'));
assert.throws(()=>selectArtDirection(all,'technical',''));
const css=artDirectionCSS(selected);
assert.match(css,/data-ig-art="technical"/);
assert.match(css,/linear-gradient/);
assert.match(css,/--ig-on-accent/);
assert.match(css,/prefers-reduced-motion/);
assert.match(css,/ig-art-chart/);
const preview=artDirectionPreview(all);
assert.equal((preview.match(/120 \/ 100/g)||[]).length,5);
assert.match(preview,/SYNTHETIC SPECIMEN/);
assert.match(artDirectionPreview(compile({...brief,theme:'<script>alert(1)</script>'})),/&lt;script&gt;/);
console.log('Art direction candidate, opaque contrast, selection, CSS and preview tests passed');
