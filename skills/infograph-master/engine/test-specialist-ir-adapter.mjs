import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fromStoryboard,attachBatch,attachStudio} from './specialist-ir-adapter.mjs';
import {validateIR,reviseIR} from './design-v3.mjs';
import {studioOutput} from '../visual-intelligence/studio-output.mjs';
const read=p=>JSON.parse(readFileSync(new URL(p,import.meta.url),'utf8'));
const model=read('./design-object-model.json'),story=read('../../narrative-design/templates/storyboard.json');
const d=fromStoryboard(story,'demo',model);
const items=['color','typography','composition','material','motion','representation'].map((studio,i)=>({blockId:'b:A1',targetId:'target'+i,strategy:studio==='representation'?'VIZ-0002':'demo',contract:studioOutput(studio,{demo:true})}));
const next=attachBatch(d,model,items);
assert.equal(d.graph.objects.length,5);
assert.equal(next.outputs.length,6);
assert.equal(next.revision,6);
assert.equal(d.outputs.length,0);
assert.deepEqual(validateIR(next,model).errors,[]);
assert.equal(reviseIR(next,model,()=>{}).outputs.length,0);
assert.throws(()=>attachStudio(d,model,{...items[0],blockId:'missing'}));
assert.throws(()=>attachBatch(d,model,[items[0],items[0]]));
assert.throws(()=>fromStoryboard({...story,acts:[{...story.acts[0],evidence_ids:[]}]},'bad',model));
