import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {initBatchLoop,beginBatch,finishBatch,rejectBatch,resumeBatch} from './system-batch-loop.mjs';
import {compileDNAAdapter} from './design-dna-adapter.mjs';
const {plan:p,ledger:l}=JSON.parse(readFileSync(new URL('./system-refactor.example.json',import.meta.url),'utf8'));
const h=c=>'sha256:'+c.repeat(64);p.sourceRef=h('a');l.sourceRef=p.sourceRef;
const s=initBatchLoop(p,l,p.sourceRef);
const started=beginBatch(p,s,{limit:2,currentRef:h('a')});assert.equal(started.batch.sliceIds.length,2);
assert.ok(started.batch.affectedSliceIds.length>=2);
assert.throws(()=>beginBatch(p,started.state,{currentRef:h('a')}),/active/);
assert.throws(()=>resumeBatch(p,s,h('b')),/changed/);
const result={batchId:started.batch.id,inputRef:h('a'),outputRef:h('b'),planFingerprint:s.planFingerprint,checks:[]};
assert.equal(finishBatch(p,started.state,result).accepted,false);
assert.throws(()=>finishBatch(p,started.state,{...result,inputRef:h('c')}),/stale/);
result.checks=started.batch.requiredChecks.map(key=>({key,status:'pass',ref:'synthetic evidence',outputRef:h('b')}));
const done=finishBatch(p,started.state,result);assert.equal(done.accepted,true);assert.equal(done.state.currentRef,h('b'));assert.equal(done.state.active,null);
assert.equal(resumeBatch(p,done.state,h('b')).counts.implemented,2);
assert.equal(resumeBatch(p,done.state,h('b')).fullDashboardComplete,false);
const retry=rejectBatch(p,started.state,'synthetic rejection',h('a'));assert.equal(retry.currentRef,h('a'));assert.equal(retry.active,null);assert.equal(beginBatch(p,retry,{currentRef:h('a')}).batch.id,'batch-2');
assert.throws(()=>resumeBatch({...p,planRevision:'p2'},done.state,h('b')),/stale/);
const c={revision:'r1',roles:[{id:'heading.primary',computedProperty:'color',target:'rgb(20, 30, 40)'},{id:'motion',target:'manual'}],exceptions:[]};
const d={sliceId:'s1',roleIds:['heading.primary','motion'],contractRevision:'r1'};
const a=compileDNAAdapter(c,d);assert.equal(a.errors.length,0);assert.ok(a.css.includes('--ig-role-heading-primary: rgb(20, 30, 40)'));assert.ok(a.css.includes('[data-ig-role~="heading.primary"]'));assert.equal(a.manual.length,1);
assert.equal(compileDNAAdapter({...c,roles:[{...c.roles[0],target:'red; background:url(x)'},c.roles[1]]},d).css,null);
assert.throws(()=>compileDNAAdapter(c,{...d,contractRevision:'old'}),/stale/);
console.log('system batch and adapter tests passed');
