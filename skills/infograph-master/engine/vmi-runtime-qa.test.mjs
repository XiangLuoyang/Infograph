import test from 'node:test';
import assert from 'node:assert/strict';
import {validateVmiRuntimePlan,evaluateVmiRuntime} from './vmi-runtime-qa.mjs';
const scene={id:'VMI-1',sliceId:'plan',dynamic:{inputs:[{id:'budget',min:0,max:100}],bindings:[{id:'level',property:'liquidHeight'}]}};
const rt={vmi:[scene]};
const runtime=budget=>({'VMI-1':{sourceRef:'Independent fixture calculation',inputs:{budget},outputs:{level:budget/5}}});
const baseline={id:'base',sliceId:'plan',kind:'baseline',steps:[],vmiRuntime:runtime(50)};
const change={id:'change',sliceId:'plan',kind:'interaction',steps:[{action:'fill',selector:'#budget',value:'80'}],vmiRuntime:runtime(80)};
const plan={cases:[baseline,change],vmiLifecycle:{'VMI-1':{heightMode:'fit',navigation:{caseIds:[],reason:'Synthetic single page only'},controls:{caseIds:['change'],reason:'Budget changes scene output'}}}};
const actual=(budget=80)=>({height:800,contentHeight:800,width:400,contentWidth:400,scrollable:true,inputs:[{id:'budget',value:budget,disabled:true}],outputs:[{id:'level',liquidHeight:budget/5},{id:'level',liquidHeight:budget/5}]});
const life=plan.vmiLifecycle['VMI-1'],expected=change.vmiRuntime['VMI-1'];
test('mandatory VMI lifecycle and changed independent expectations',()=>{
 assert.equal(validateVmiRuntimePlan(plan,rt),plan);
 assert.throws(()=>validateVmiRuntimePlan({cases:plan.cases},rt),/lifecycle/);
 const missing=structuredClone(plan);delete missing.cases[1].vmiRuntime;
 assert.throws(()=>validateVmiRuntimePlan(missing,rt),/expectations/);
 const unchanged=structuredClone(plan);unchanged.cases[1].vmiRuntime=runtime(50);
 assert.throws(()=>validateVmiRuntimePlan(unchanged,rt),/changed input AND output/);
 const wrong=structuredClone(plan);wrong.vmiLifecycle['VMI-1'].navigation.caseIds=['change'];
 assert.throws(()=>validateVmiRuntimePlan(wrong,rt),/lifecycle case/);
 const noControls=structuredClone(plan);noControls.vmiLifecycle['VMI-1'].controls.caseIds=[];
 assert.throws(()=>validateVmiRuntimePlan(noControls,rt),/host control/);
 const staticScene={id:'VMI-1',sliceId:'plan',dynamic:null};
 assert.equal(validateVmiRuntimePlan(plan,{vmi:[staticScene]}),plan);
 assert.equal(validateVmiRuntimePlan({cases:[]},null).cases.length,0);
});
test('actual fit, scroll, locked host controls and both responsive output copies',()=>{
 assert.equal(evaluateVmiRuntime(scene,life,expected,actual()).ok,true);
 assert.ok(evaluateVmiRuntime(scene,life,expected,{...actual(),contentHeight:900}).issues.includes('frame-content-clipped'));
 assert.ok(evaluateVmiRuntime(scene,{...life,heightMode:'scroll'},expected,{...actual(),contentHeight:900}).ok);
 assert.ok(!evaluateVmiRuntime(scene,{...life,heightMode:'scroll'},expected,{...actual(),contentHeight:900,scrollable:false}).ok);
 assert.ok(!evaluateVmiRuntime(scene,life,expected,{...actual(),contentWidth:500}).ok);
 assert.ok(!evaluateVmiRuntime(scene,life,expected,actual(50)).ok);
 const unlocked=actual();unlocked.inputs[0].disabled=false;
 assert.ok(!evaluateVmiRuntime(scene,life,expected,unlocked).ok);
 const partial=actual();partial.outputs[1].liquidHeight=10;
 assert.ok(!evaluateVmiRuntime(scene,life,expected,partial).ok);
 const absent=actual();absent.outputs.pop();
 assert.ok(!evaluateVmiRuntime(scene,life,expected,absent).ok);
});
